import test from 'node:test';
import assert from 'node:assert/strict';
import { FILE_LIMITS, checkFileLimits, fileKind, lineCount, sizeViolations, validateFileLimits } from '../file-limits.js';
import { validateConfig, effectiveConfig } from '../config.js';

const project = '/p';
const lines = n => Array.from({ length: n }, (_, i) => `line ${i}`).join('\n') + '\n';
// Fixture keys are POSIX paths; on Windows `path.resolve('/p', 'a.js')` yields `C:\p\a.js`, so strip the drive
// and normalise separators before looking a file up.
const posix = path => path.replace(/^[A-Za-z]:/, '').split('\\').join('/');
const fsOf = files => path => files[posix(path)];
const check = (exec, files, extra = {}) => checkFileLimits(exec, FILE_LIMITS, { project, cwd: project, read: fsOf(files), ...extra });

test('lineCount 与文件分类', () => {
  assert.equal(lineCount(''), 0);
  assert.equal(lineCount('a\nb\n'), 2);
  assert.equal(lineCount('a\nb'), 2);
  assert.equal(fileKind('src/a.js'), 'source');
  assert.equal(fileKind('tests/a.test.mjs'), 'test');
  assert.equal(fileKind('README.md'), undefined);
  assert.equal(fileKind('node_modules/x/a.js'), undefined);
  assert.equal(fileKind('pnpm-lock.yaml'), undefined);
});

test('新建源文件超过 500 行被拒，不超过时放行', () => {
  assert.match(check({ name: 'write', arguments: { file_path: 'a.js', content: lines(501) } }, {}), /above the source file limit 500/);
  assert.equal(check({ name: 'write', arguments: { file_path: 'a.js', content: lines(500) } }, {}), undefined);
  assert.equal(check({ name: 'write', arguments: { file_path: 'tests/a.test.mjs', content: lines(800) } }, {}), undefined);
  assert.match(check({ name: 'write', arguments: { file_path: 'tests/a.test.mjs', content: lines(801) } }, {}), /test file limit 800/);
});

test('已有文件不能用 write 整体覆盖', () => {
  assert.match(check({ name: 'write', arguments: { file_path: 'a.md', content: 'x' } }, { '/p/a.md': 'old' }), /use edit/);
  assert.match(check({ name: 'str_replace_editor', arguments: { command: 'create', path: 'a.js', file_text: 'x' } }, { '/p/a.js': 'old' }), /use edit/);
});

test('超标文件只能减不能增', () => {
  const big = { '/p/big.js': lines(900) };
  assert.match(check({ name: 'edit', arguments: { file_path: 'big.js', old_string: 'line 1\n', new_string: 'line 1\nextra\n' } }, big), /may only shrink/);
  assert.equal(check({ name: 'edit', arguments: { file_path: 'big.js', old_string: 'line 1\n', new_string: '' } }, big), undefined);
  assert.equal(check({ name: 'edit', arguments: { file_path: 'big.js', old_string: 'line 1\n', new_string: 'LINE 1\n' } }, big), undefined, '同行数修改可以');
});

test('edit 让文件越过上限时被拒', () => {
  const near = { '/p/a.js': lines(500) };
  assert.match(check({ name: 'edit', arguments: { file_path: 'a.js', old_string: 'line 3\n', new_string: 'line 3\nmore\n' } }, near), /would have 501 lines/);
  assert.match(check({ name: 'str_replace_editor', arguments: { command: 'str_replace', path: 'a.js', old_str: 'line 3\n', new_str: 'line 3\nmore\n' } }, near), /would have 501 lines/);
});

test('生成文件不能直接改，也不受整读限制', () => {
  const gen = { '/p/client.js': '// @generated by x\n' + lines(3000) };
  assert.match(check({ name: 'edit', arguments: { file_path: 'client.js', old_string: 'line 1\n', new_string: '' } }, gen), /generated/);
  assert.equal(check({ name: 'read', arguments: { file_path: 'client.js' } }, gen), undefined);
});

test('大文件不能整读，带 limit 小段读可以', () => {
  const files = { '/p/a.js': lines(450) };
  assert.match(check({ name: 'read', arguments: { file_path: 'a.js' } }, files), /Locate with grep first/);
  assert.match(check({ name: 'read', arguments: { file_path: 'a.js', limit: 401 } }, files), /whole-read limit/);
  assert.equal(check({ name: 'read', arguments: { file_path: 'a.js', offset: 100, limit: 120 } }, files), undefined);
  assert.equal(check({ name: 'read', arguments: { file_path: 'notes.md' } }, { '/p/notes.md': lines(2000) }), undefined);
});

test('队友汇报超长被拒，主控派活说明不限', () => {
  const long = { name: 'send_message', arguments: { target: 'lead', message: '字'.repeat(1501) } };
  assert.match(check(long, {}), /Split it into messages/);
  assert.equal(check(long, {}, { role: 'lead' }), undefined);
});

test('项目外路径交给 access 处理；关闭后不拦截', () => {
  assert.equal(check({ name: 'write', arguments: { file_path: '../x.js', content: lines(900) } }, {}), undefined);
  assert.equal(checkFileLimits({ name: 'write', arguments: { file_path: 'a.js', content: lines(900) } }, false, { project, cwd: project, read: () => undefined }), undefined);
});

test('fileLimits 配置校验：默认值、合并、false 关闭、非法值', () => {
  assert.deepEqual(validateFileLimits(undefined), FILE_LIMITS);
  assert.equal(validateFileLimits(false), false);
  assert.equal(validateFileLimits({ sourceMax: 600 }).sourceMax, 600);
  assert.throws(() => validateFileLimits({ bogus: 1 }), /does not support fields/);
  assert.throws(() => validateFileLimits({ sourceMax: 10 }), /50 to 20000/);
  assert.throws(() => validateFileLimits({ sourceWarn: 700, sourceMax: 600 }), /must not exceed/);
  assert.equal(effectiveConfig({}).workflow.fileLimits, false);
  assert.deepEqual(effectiveConfig({ workflow: { fileLimits: {} } }).workflow.fileLimits, FILE_LIMITS);
});

test('备选模型最多 3 个', () => {
  const cfg = effectiveConfig({});
  const [id, c] = Object.entries(cfg.capabilities).find(([, v]) => v.provider) ?? [];
  if (!id) return;
  const fb = Array.from({ length: 4 }, (_, i) => ({ provider: 'p', model: `m${i}` }));
  assert.throws(() => validateConfig({ ...cfg, capabilities: { ...cfg.capabilities, [id]: { ...c, fallbacks: fb } } }), /at most 3/);
});

test('sizeViolations 跳过生成文件与非代码文件', () => {
  const files = { 'a.js': lines(501), 'b.md': lines(9000), 'c.js': '// @generated\n' + lines(9000), 'tests/t.test.mjs': lines(801) };
  const out = sizeViolations(Object.keys(files), FILE_LIMITS, path => files[posix(path).replace(/^\/r\//, '')], '/r');
  assert.deepEqual(out.map(v => v.file).sort(), ['a.js', 'tests/t.test.mjs']);
});
