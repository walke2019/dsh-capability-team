// Assembles the shipped client.js from client/*.js. DSH loads one client script per package (its own client
// packages are bundled the same way), so the sources stay small while the published file stays single.
// Fragments share the factory scope in file-name order; the last one defines `plugin`. No transpiling.
// `--check` fails when client.js is stale instead of rewriting it.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const GENERATED = '// @generated by scripts/build-client.mjs from client/*.js — edit those files, then run npm run build:client.';
const HEAD = `${GENERATED}
// Web cards and the right-sidebar overview for the capability-team tools. React comes from the host module
// table; no other Harness Client package is required (host tokens are the only shared styling dependency).
window.__ModuleLoader__.load({
  id: 'dsh-capability-team',
  factory(require) {
`;
const TAIL = `
    return plugin;
  },
});
`;
export async function buildClient() {
  const dir = join(root, 'client');
  const names = (await readdir(dir)).filter(name => /^\d{2}[a-z]?-[a-z0-9-]+\.js$/.test(name)).sort();
  if (!names.length) throw new Error('client/ has no fragments');
  const parts = await Promise.all(names.map(name => readFile(join(dir, name), 'utf8')));
  return HEAD + parts.map(text => text.replace(/\n+$/, '\n')).join('\n') + TAIL;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, 'client.js');
  const next = await buildClient();
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== next) { console.error('client.js is stale: run npm run build:client'); process.exit(1); }
    console.log('CLIENT_OK');
  } else {
    await writeFile(target, next);
    console.log(`client.js built from client/ (${next.split('\n').length} lines)`);
  }
}
