// Assembles client.js from client/*.js (same scheme as the root package): fragments share one factory scope in
// file-name order and the last one defines `plugin`. No transpiling. `--check` fails on a stale client.js.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const GENERATED = '// @generated by packages/autocomplete/scripts/build-client.mjs from client/*.js — edit those files, then run npm run build:autocomplete.';
const HEAD = `${GENERATED}
// Composer ghost-text suggestions and the settings card. React comes from the host module table.
window.__ModuleLoader__.load({
  id: '@aiwuk/autocomplete',
  factory(require) {
`;
const TAIL = `
    return plugin;
  },
});
`;
export async function buildClient() {
  const dir = join(root, 'client');
  const names = (await readdir(dir)).filter(name => /^\d{2}[a-z]?-[a-z0-9-]+\.js$/.test(name)).sort();
  if (!names.length) throw new Error('client/ has no fragments');
  const parts = await Promise.all(names.map(name => readFile(join(dir, name), 'utf8')));
  return HEAD + parts.map(text => text.replace(/\n+$/, '\n')).join('\n') + TAIL;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = join(root, 'client.js');
  const next = await buildClient();
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8').catch(() => '')) !== next) { console.error('autocomplete client.js is stale: run npm run build:autocomplete'); process.exit(1); }
    console.log('AUTOCOMPLETE_CLIENT_OK');
  } else {
    await writeFile(target, next);
    console.log(`autocomplete client.js built (${next.split('\n').length} lines)`);
  }
}
